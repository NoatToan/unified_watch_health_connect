/**
 * "Dáng chạy đúng" — the 9-frame running-gait-cycle reference opened from [TrainingScreen]'s
 * [RunningFormEntryCard]. Source image: Wikimedia Commons' `Run_cycle.jpg` (1180×399, CC BY-SA 4.0,
 * author "BoH") — pre-sliced into 9 individual `run_cycle_frame_<n>.webp` drawables checked into this
 * module (`res/drawable-nodpi/`), not cropped at runtime from one bundled/downloaded image: the 9
 * runner poses in the source aren't evenly spaced columns (verified by inspecting the actual pixel
 * layout — poses cluster tightly around each foot-strike, 30-40%/80-90% especially), so a precise
 * one-time offline slice is both simpler and more reliable than reproducing that same irregular-column
 * math as runtime crop/offset logic in Compose. `drawable-nodpi` (not a density bucket) matches this
 * project's only other bundled-bitmap precedent (`core/designsystem`'s `watch_<id>.webp`, generated by
 * `scripts/gen_watch_catalog.py`) — these are fixed pre-sized illustrations, not something that should
 * be re-rasterized per density.
 *
 * [GAIT_FRAMES] tracks ONE leg continuously across the whole bilateral image (both left- and
 * right-leg poses are the same 6 named gait phases, just mirrored halves of one cycle) rather than
 * inventing 9 unrelated labels: frame 9 is the same phase as frame 1 (foot-strike again), closing the
 * loop — which is also exactly what makes the animated-loop mode below read as a seamless cycle
 * instead of visibly "snapping back" at the end.
 *
 * Two view modes per the brief: [ViewMode.StepByStep] ([HorizontalPager] + prev/next buttons, one
 * frame at a time with its own phase label + cue) and [ViewMode.AnimatedLoop] (the same 9 frames
 * auto-advancing on a timer, flipbook-style, with play/pause) — a [SingleChoiceSegmentedButtonRow]
 * toggles between them, both reusing the same [GAIT_FRAMES] data and the same [FrameDetail].
 *
 * [LicenseAttribution] is pinned below both modes (not just one) since CC BY-SA 4.0 requires visible
 * attribution wherever the (derived, cropped) image is shown.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
internal fun RunningFormScreen(onBack: () -> Unit) {
    var mode by rememberSaveable { mutableStateOf(ViewMode.StepByStep) }
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Dáng chạy đúng") },
                // D-1189: app chrome, not this screen's own content — restores the normal ripple.
                navigationIcon = {
                    ChromeRipple {
                        IconButton(onClick = onBack) {
                            Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                        }
                    }
                },
            )
        },
    ) { padding ->
        Column(
            Modifier.fillMaxSize().padding(padding).padding(Spacing.lg).testTag("running_form_screen"),
            verticalArrangement = Arrangement.spacedBy(Spacing.lg),
        ) {
            ModeToggle(mode, onModeChange = { mode = it })
            when (mode) {
                ViewMode.StepByStep -> StepByStepContent(Modifier.weight(1f))
                ViewMode.AnimatedLoop -> AnimatedLoopContent(Modifier.weight(1f))
            }
            LicenseAttribution()
        }
    }
}

private enum class ViewMode { StepByStep, AnimatedLoop }

@Composable
private fun ModeToggle(mode: ViewMode, onModeChange: (ViewMode) -> Unit) {
    SingleChoiceSegmentedButtonRow(Modifier.fillMaxWidth().testTag("running_form_mode_toggle")) {
        SegmentedButton(
            selected = mode == ViewMode.StepByStep,
            onClick = { onModeChange(ViewMode.StepByStep) },
            shape = SegmentedButtonDefaults.itemShape(index = 0, count = 2),
            modifier = Modifier.testTag("running_form_mode_step_by_step"),
        ) { Text("Từng bước") }
        SegmentedButton(
            selected = mode == ViewMode.AnimatedLoop,
            onClick = { onModeChange(ViewMode.AnimatedLoop) },
            shape = SegmentedButtonDefaults.itemShape(index = 1, count = 2),
            modifier = Modifier.testTag("running_form_mode_loop"),
        ) { Text("Vòng lặp") }
    }
}

/** Swipeable [HorizontalPager] plus explicit prev/next buttons (both requested in the brief — swipe
 *  alone isn't discoverable, buttons alone don't feel as natural for "flip through frames"). */
@Composable
private fun StepByStepContent(modifier: Modifier = Modifier) {
    val pagerState = rememberPagerState(pageCount = { GAIT_FRAMES.size })
    val scope = rememberCoroutineScope()
    Column(modifier, verticalArrangement = Arrangement.spacedBy(Spacing.md)) {
        HorizontalPager(
            state = pagerState,
            modifier = Modifier.fillMaxWidth().weight(1f).testTag("running_form_pager"),
        ) { page ->
            FrameDetail(GAIT_FRAMES[page])
        }
        Row(
            Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically,
        ) {
            IconButton(
                onClick = { scope.launch { pagerState.animateScrollToPage((pagerState.currentPage - 1).coerceAtLeast(0)) } },
                enabled = pagerState.currentPage > 0,
                modifier = Modifier.testTag("running_form_prev"),
            ) { Icon(Icons.AutoMirrored.Filled.KeyboardArrowLeft, contentDescription = "Khung trước") }
            FrameDots(pagerState.currentPage, GAIT_FRAMES.size)
            IconButton(
                onClick = {
                    scope.launch { pagerState.animateScrollToPage((pagerState.currentPage + 1).coerceAtMost(GAIT_FRAMES.size - 1)) }
                },
                enabled = pagerState.currentPage < GAIT_FRAMES.size - 1,
                modifier = Modifier.testTag("running_form_next"),
            ) { Icon(Icons.AutoMirrored.Filled.KeyboardArrowRight, contentDescription = "Khung tiếp theo") }
        }
    }
}

@Composable
private fun FrameDots(currentPage: Int, pageCount: Int) {
    Row(horizontalArrangement = Arrangement.spacedBy(Spacing.xs), verticalAlignment = Alignment.CenterVertically) {
        repeat(pageCount) { index ->
            val color = if (index == currentPage) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.surfaceVariant
            Box(Modifier.size(DotSize).background(color, CircleShape))
        }
    }
}

private val DotSize = 6.dp

/** Auto-advancing flipbook: a free-running timer cycles [currentFrame] through all 9 poses, looping
 *  forever while [isPlaying] — pausing just freezes on whatever frame is showing rather than resetting
 *  to frame 0, so resuming continues the loop instead of restarting it. */
@Composable
private fun AnimatedLoopContent(modifier: Modifier = Modifier) {
    var currentFrame by rememberSaveable { mutableIntStateOf(0) }
    var isPlaying by rememberSaveable { mutableStateOf(true) }

    LaunchedEffect(isPlaying) {
        if (!isPlaying) return@LaunchedEffect
        while (true) {
            delay(LoopFrameDelayMs)
            currentFrame = (currentFrame + 1) % GAIT_FRAMES.size
        }
    }

    Column(modifier, verticalArrangement = Arrangement.spacedBy(Spacing.md)) {
        Box(Modifier.weight(1f).testTag("running_form_loop_frame")) {
            FrameDetail(GAIT_FRAMES[currentFrame])
        }
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.Center) {
            IconButton(onClick = { isPlaying = !isPlaying }, modifier = Modifier.testTag("running_form_play_pause")) {
                Icon(
                    if (isPlaying) Icons.Filled.Pause else Icons.Filled.PlayArrow,
                    contentDescription = if (isPlaying) "Tạm dừng" else "Phát",
                )
            }
        }
    }
}

private const val LoopFrameDelayMs = 450L

/** One frame's image + phase label + biomechanical cue — shared by both view modes. */
@Composable
private fun FrameDetail(frame: GaitFrame) {
    Column(Modifier.fillMaxSize(), verticalArrangement = Arrangement.spacedBy(Spacing.sm)) {
        Box(
            Modifier
                .fillMaxWidth()
                .aspectRatio(FrameAspectRatio)
                .background(MaterialTheme.colorScheme.surfaceVariant),
        ) {
            // contentDescription null: the phase name is already shown as visible text right below,
            // so a screen reader announcing it a second time off the image itself would be redundant.
            Image(
                painter = painterResource(frame.imageRes),
                contentDescription = null,
                contentScale = ContentScale.Fit,
                modifier = Modifier.fillMaxSize().padding(Spacing.lg),
            )
        }
        Text(
            "${frame.percent}% chu kỳ — ${frame.phase}",
            style = MaterialTheme.typography.titleMedium,
            modifier = Modifier.testTag("running_form_frame_phase"),
        )
        Text(
            frame.cue,
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            modifier = Modifier.testTag("running_form_frame_cue"),
        )
    }
}

