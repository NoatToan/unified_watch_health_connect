private const val IMAGE_SOURCE_URL = "https://upload.wikimedia.org/wikipedia/commons/4/4e/Run_cycle.jpg"
private const val LICENSE_URL = "https://creativecommons.org/licenses/by-sa/4.0/"

/** CC BY-SA 4.0 requires visible attribution + a link to the license wherever this (derived, cropped)
 *  image is used — kept small/unobtrusive per the brief, but always on screen in both view modes
 *  (outside the `when` in [RunningFormScreen]), not just one. */
@Composable
private fun LicenseAttribution() {
    val context = LocalContext.current
    Column(Modifier.fillMaxWidth().testTag("running_form_attribution"), verticalArrangement = Arrangement.spacedBy(Spacing.xxs)) {
        Text(
            "Ảnh: BoH, Wikimedia Commons",
            style = MaterialTheme.typography.labelSmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        Row(horizontalArrangement = Arrangement.spacedBy(Spacing.sm)) {
            AttributionLinkButton("Nguồn ảnh", IMAGE_SOURCE_URL, context::openUrl, Modifier.testTag("running_form_attribution_source"))
            AttributionLinkButton("CC BY-SA 4.0", LICENSE_URL, context::openUrl, Modifier.testTag("running_form_attribution_license"))
        }
    }
}

@Composable
private fun AttributionLinkButton(label: String, url: String, onOpen: (String) -> Unit, modifier: Modifier = Modifier) {
    TextButton(onClick = { onOpen(url) }, modifier = modifier, contentPadding = PaddingValues(horizontal = Spacing.xs)) {
        Text(label, style = MaterialTheme.typography.labelSmall)
    }
}

/** Swallows failures (no browser installed, malformed URL, …) — a tap on an attribution link must
 *  never crash the app. Mirrors `feature/gear`'s `GearDetailCta`'s own plain-`ACTION_VIEW` pattern:
 *  a one-off external link doesn't need `core/designsystem`'s Chrome Custom Tabs helper. */
private fun Context.openUrl(url: String) {
    runCatching { startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(url))) }
}
